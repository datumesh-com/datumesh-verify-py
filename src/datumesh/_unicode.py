"""Unicode 15.1 string checks (SPEC.md 3.5), independent of the runtime's unicodedata.

The tables come from _ucd15.py, generated by tools/gen_unicode.py with Python
3.13 (unicodedata 15.1.0). Nothing here consults the ``unicodedata`` module, so
results are the same on every Python version.
"""

from __future__ import annotations

from bisect import bisect_right
from typing import Dict, List, Tuple

from . import _ucd15

UNIDATA_VERSION = _ucd15.UNIDATA_VERSION

_ASSIGNED_STARTS = [a for a, _ in _ucd15.ASSIGNED]
_ASSIGNED_ENDS = [b for _, b in _ucd15.ASSIGNED]

_CCC: Dict[int, int] = {}
for _a, _b, _c in _ucd15.CCC:
    for _cp in range(_a, _b + 1):
        _CCC[_cp] = _c

_NFD: Dict[int, Tuple[int, ...]] = {}
for _chunk in _ucd15.NFD:
    for _item in _chunk.split(";"):
        if _item:
            _k, _v = _item.split(":")
            _NFD[int(_k, 16)] = tuple(int(x, 16) for x in _v.split())

_COMPOSE: Dict[Tuple[int, int], int] = {}
_SECOND: set[int] = set()
for _chunk in _ucd15.COMPOSE:
    for _item in _chunk.split(";"):
        if _item:
            _k, _v = _item.split(":")
            _first, _second = (int(x, 16) for x in _v.split())
            _COMPOSE[(_first, _second)] = int(_k, 16)
            _SECOND.add(_second)

_NFC_NO: set[int] = set()
for _a, _b in _ucd15.NFC_NO:
    _NFC_NO.update(range(_a, _b + 1))

# Hangul (Unicode 3.12).
_S_BASE, _L_BASE, _V_BASE, _T_BASE = 0xAC00, 0x1100, 0x1161, 0x11A7
_L_COUNT, _V_COUNT, _T_COUNT = 19, 21, 28
_N_COUNT = _V_COUNT * _T_COUNT
_S_COUNT = _L_COUNT * _N_COUNT

# NFC_Quick_Check=Maybe: characters that can combine with a preceding character.
_NFC_MAYBE = set(_SECOND)
_NFC_MAYBE.update(range(_V_BASE, _V_BASE + _V_COUNT))
_NFC_MAYBE.update(range(_T_BASE + 1, _T_BASE + _T_COUNT))


def is_assigned(cp: int) -> bool:
    """True when ``cp`` has General_Category other than Cn in Unicode 15.1."""
    i = bisect_right(_ASSIGNED_STARTS, cp) - 1
    return i >= 0 and cp <= _ASSIGNED_ENDS[i]


def combining_class(cp: int) -> int:
    return _CCC.get(cp, 0)


def _decompose(s: str) -> List[int]:
    out: List[int] = []
    for ch in s:
        cp = ord(ch)
        if _S_BASE <= cp < _S_BASE + _S_COUNT:
            idx = cp - _S_BASE
            out.append(_L_BASE + idx // _N_COUNT)
            out.append(_V_BASE + (idx % _N_COUNT) // _T_COUNT)
            t = idx % _T_COUNT
            if t:
                out.append(_T_BASE + t)
        else:
            d = _NFD.get(cp)
            if d is None:
                out.append(cp)
            else:
                out.extend(d)
    # Canonical ordering: stable sort of each run of non-starters by combining class.
    i, n = 0, len(out)
    while i < n:
        if _CCC.get(out[i], 0) == 0:
            i += 1
            continue
        j = i
        while j < n and _CCC.get(out[j], 0) != 0:
            j += 1
        if j - i > 1:
            out[i:j] = sorted(out[i:j], key=lambda c: _CCC[c])
        i = j
    return out


def _compose(cps: List[int]) -> List[int]:
    if not cps:
        return cps
    out: List[int] = []
    starter_idx = -1
    last_ccc = -1
    for cp in cps:
        ccc = _CCC.get(cp, 0)
        if starter_idx >= 0:
            starter = out[starter_idx]
            blocked = last_ccc != -1 and (last_ccc == 0 or last_ccc >= ccc)
            # last_ccc is the class of the previous character kept after the starter;
            # -1 means the starter is immediately before this character.
            if not blocked:
                composite = None
                if _L_BASE <= starter < _L_BASE + _L_COUNT and _V_BASE <= cp < _V_BASE + _V_COUNT:
                    composite = _S_BASE + ((starter - _L_BASE) * _V_COUNT + (cp - _V_BASE)) * _T_COUNT
                elif (_S_BASE <= starter < _S_BASE + _S_COUNT and (starter - _S_BASE) % _T_COUNT == 0
                      and _T_BASE < cp < _T_BASE + _T_COUNT):
                    composite = starter + (cp - _T_BASE)
                else:
                    composite = _COMPOSE.get((starter, cp))
                if composite is not None:
                    out[starter_idx] = composite
                    continue
        if ccc == 0:
            starter_idx = len(out)
            last_ccc = -1
        else:
            last_ccc = ccc
        out.append(cp)
    return out


def nfc(s: str) -> str:
    """Normalization Form C of ``s`` under Unicode 15.1."""
    return "".join(map(chr, _compose(_decompose(s))))


def is_nfc(s: str) -> bool:
    """True when ``s`` is in Normalization Form C under Unicode 15.1 (UAX #15 quick check, then full check)."""
    last = 0
    maybe = False
    for ch in s:
        cp = ord(ch)
        if cp < 0x300:
            last = 0
            continue
        ccc = _CCC.get(cp, 0)
        if ccc and last > ccc:
            return False
        if cp in _NFC_NO:
            return False
        if cp in _NFC_MAYBE:
            maybe = True
        last = ccc
    if not maybe:
        return True
    return nfc(s) == s
