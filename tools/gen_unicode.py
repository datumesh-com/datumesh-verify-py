#!/usr/bin/env python3
"""Generate src/datumesh/_ucd15.py: the Unicode 15.1 data datumesh needs.

SPEC.md 3.5 pins string validity to Unicode 15.1 (assigned code points and NFC).
Python 3.10's unicodedata is Unicode 13, so the package ships its own tables,
generated from a Python whose unicodedata is exactly 15.1.0 (Python 3.13):

    docker run --rm -v "$PWD":/w -w /w python:3.13-slim python tools/gen_unicode.py

It also writes tests/fixtures/unicode15.json, results computed here with the
15.1 unicodedata, which the test suite checks on every Python version.

Tables written:
- ASSIGNED: inclusive ranges with General_Category != Cn.
- CCC: canonical combining class of every code point whose class is not 0.
- NFD: full canonical decomposition of every code point that has one
  (Hangul syllables excluded; they are decomposed algorithmically).
- COMPOSE: primary composites and their two-code-point canonical
  decomposition (pairs the NFC composition step may join).
- NFC_NO: code points that never occur in NFC text (NFC_Quick_Check=No).
"""

from __future__ import annotations

import json
import pathlib
import random
import sys
import unicodedata

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "src" / "datumesh" / "_ucd15.py"
FIXTURES = ROOT / "tests" / "fixtures" / "unicode15.json"

HANGUL_S_BASE, HANGUL_S_COUNT = 0xAC00, 11172


def is_hangul_syllable(cp: int) -> bool:
    return HANGUL_S_BASE <= cp < HANGUL_S_BASE + HANGUL_S_COUNT


def ranges(cps: list[int]) -> list[tuple[int, int]]:
    out: list[tuple[int, int]] = []
    for cp in cps:
        if out and out[-1][1] == cp - 1:
            out[-1] = (out[-1][0], cp)
        else:
            out.append((cp, cp))
    return out


def hexs(cps) -> str:
    return " ".join("%04X" % c for c in cps)


def main() -> int:
    if unicodedata.unidata_version != "15.1.0":
        print(f"need unicodedata 15.1.0 (Python 3.13), have {unicodedata.unidata_version}", file=sys.stderr)
        return 1
    assigned: list[int] = []
    ccc: dict[int, int] = {}
    nfd: dict[int, str] = {}
    compose: dict[int, tuple[int, int]] = {}
    nfc_no: list[int] = []
    for cp in range(0x110000):
        ch = chr(cp)
        if unicodedata.category(ch) != "Cn":
            assigned.append(cp)
        c = unicodedata.combining(ch)
        if c:
            ccc[cp] = c
        if 0xD800 <= cp <= 0xDFFF:
            continue
        if not is_hangul_syllable(cp):
            d = unicodedata.normalize("NFD", ch)
            if d != ch:
                nfd[cp] = d
            raw = unicodedata.decomposition(ch)
            if raw and not raw.startswith("<"):
                parts = [int(x, 16) for x in raw.split()]
                if len(parts) == 2 and unicodedata.normalize("NFC", ch) == ch:
                    compose[cp] = (parts[0], parts[1])
        if unicodedata.normalize("NFC", ch) != ch:
            nfc_no.append(cp)

    lines = [
        '"""Unicode 15.1.0 tables for datumesh. GENERATED by tools/gen_unicode.py; do not edit."""',
        "",
        'UNIDATA_VERSION = "15.1.0"',
        "",
        "# Inclusive ranges of assigned code points (General_Category != Cn).",
        "ASSIGNED = (",
    ]
    for a, b in ranges(assigned):
        lines.append(f"    (0x{a:04X}, 0x{b:04X}),")
    lines.append(")")
    lines.append("")
    lines.append("# Canonical combining classes: (first, last, class) for runs with the same class.")
    lines.append("CCC = (")
    run: list[list[int]] = []
    for cp in sorted(ccc):
        if run and run[-1][1] == cp - 1 and run[-1][2] == ccc[cp]:
            run[-1][1] = cp
        else:
            run.append([cp, cp, ccc[cp]])
    for a, b, c in run:
        lines.append(f"    (0x{a:04X}, 0x{b:04X}, {c}),")
    lines.append(")")
    lines.append("")
    lines.append("# Full canonical decompositions, 'CP:CP CP ...;' (Hangul syllables are algorithmic).")
    lines.append("NFD = (")
    items = [f"{cp:04X}:{hexs(map(ord, d))};" for cp, d in sorted(nfd.items())]
    for i in range(0, len(items), 6):
        lines.append("    " + repr("".join(items[i:i + 6])) + ",")
    lines.append(")")
    lines.append("")
    lines.append("# Primary composites and their canonical pair, 'CP:FIRST SECOND;'.")
    lines.append("COMPOSE = (")
    items = [f"{cp:04X}:{a:04X} {b:04X};" for cp, (a, b) in sorted(compose.items())]
    for i in range(0, len(items), 6):
        lines.append("    " + repr("".join(items[i:i + 6])) + ",")
    lines.append(")")
    lines.append("")
    lines.append("# Code points with NFC_Quick_Check=No, as inclusive ranges.")
    lines.append("NFC_NO = (")
    for a, b in ranges(nfc_no):
        lines.append(f"    (0x{a:04X}, 0x{b:04X}),")
    lines.append(")")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")

    # Fixtures: NFC verdicts computed with the real 15.1 unicodedata, for strings whose
    # verdict differs between Unicode versions or exercises every part of the algorithm.
    rnd = random.Random(15_1)
    marks = sorted(ccc)
    starters = [cp for cp in assigned if cp not in ccc and not 0xD800 <= cp <= 0xDFFF and cp < 0x30000]
    samples: list[str] = [
        "a\U0001E08F̖",  # U+1E08F (Unicode 15.0, ccc 230) out of canonical order
        "a̖\U0001E08F",
        "가",  # conjoining jamo compose to a syllable
        "각",
        "̈́",  # NFC_QC=No
        "é", "é", "Zürich", "Zürich",
        "क़",  # composition exclusion
        "\U0001611E\U0001611E\U0001611F",  # Kirat Rai vowel signs (16.0, unassigned in 15.1)
        "\U00011383\U000113C9",  # 16.0 composition pair, unassigned in 15.1
        "ೋ",
        "ᬆ",
    ]
    for cp in nfd:
        samples.append(chr(cp))
        samples.append(nfd[cp])
    for cp in compose:
        a, b = compose[cp]
        samples.append(chr(a) + chr(b))
    for _ in range(20000):
        n = rnd.randint(1, 6)
        s = "".join(chr(rnd.choice(marks)) if rnd.random() < 0.5 else chr(rnd.choice(starters)) for _ in range(n))
        samples.append(s)
    for _ in range(5000):
        cp = rnd.choice(list(nfd))
        s = unicodedata.normalize("NFD", chr(cp)) + chr(rnd.choice(marks))
        samples.append(s)
        samples.append(unicodedata.normalize("NFC", s))
    seen: set[str] = set()
    fixtures = []
    for s in samples:
        if s in seen:
            continue
        seen.add(s)
        fixtures.append([s, unicodedata.is_normalized("NFC", s)])
    FIXTURES.parent.mkdir(parents=True, exist_ok=True)
    FIXTURES.write_text(json.dumps({"unidata_version": "15.1.0", "nfc": fixtures}, ensure_ascii=True), encoding="ascii")
    print(f"assigned ranges {len(ranges(assigned))}, ccc runs {len(run)}, nfd {len(nfd)}, compose {len(compose)}, "
          f"nfc_no ranges {len(ranges(nfc_no))}, fixtures {len(fixtures)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
