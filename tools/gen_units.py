#!/usr/bin/env python3
"""Generate src/datumesh/_unitlist.py: the unit list of spec/units.md.

units.md (part of spec-0.4.1, normative) lists the
literal units in fenced blocks tagged ``units-currency``, ``units-physical`` and
``units-ratio``; those blocks are the machine-readable list. This script copies them, in file order,
into the package, together with the SHA-256 of the units.md it read:

    python3 tools/gen_units.py            # write the module
    python3 tools/gen_units.py --check    # exit 1 if the module differs from what units.md gives

Index units (``index:<period>=<value>``, units.md 2.4) are a pattern, not a
list; they are checked in code.
"""

from __future__ import annotations

import hashlib
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SOURCE = ROOT / "spec" / "units.md"
OUT = ROOT / "src" / "datumesh" / "_unitlist.py"

TAGS = ("units-currency", "units-physical", "units-ratio")
_FENCE = re.compile(r"^```([A-Za-z0-9_-]*)[ \t]*\n(.*?)^```[ \t]*$", re.M | re.S)


def read_blocks(text: str) -> dict:
    blocks: dict = {tag: [] for tag in TAGS}
    for tag, body in _FENCE.findall(text):
        if tag.startswith("units-"):
            if tag not in blocks:
                raise SystemExit(f"units.md has an unknown block tag {tag!r}")
            blocks[tag].extend(body.split())
    for tag, items in blocks.items():
        if not items:
            raise SystemExit(f"units.md has no {tag} block")
        if len(set(items)) != len(items):
            raise SystemExit(f"{tag} lists a unit twice")
    return blocks


def render(raw: bytes) -> str:
    blocks = read_blocks(raw.decode("utf-8"))

    def tuple_lines(items: list) -> str:
        out, line = [], "    "
        for item in items:
            piece = repr(item) + ", "
            if len(line) + len(piece) > 100:
                out.append(line.rstrip())
                line = "    "
            line += piece
        out.append(line.rstrip())
        return "\n".join(out)

    return (
        '"""The unit list of spec/units.md (spec-0.4.1). Generated by tools/gen_units.py; do not edit."""\n\n'
        f'SOURCE_SHA256 = "{hashlib.sha256(raw).hexdigest()}"\n\n'
        "#: ```units-currency``` blocks, in file order (ISO 4217 List One without XXX, then withdrawn codes).\n"
        f"CURRENCY = (\n{tuple_lines(blocks['units-currency'])}\n)\n\n"
        "#: ```units-physical```\n"
        f"PHYSICAL = (\n{tuple_lines(blocks['units-physical'])}\n)\n\n"
        "#: ```units-ratio```\n"
        f"RATIO = (\n{tuple_lines(blocks['units-ratio'])}\n)\n"
    )


def main() -> int:
    text = render(SOURCE.read_bytes())
    if "--check" in sys.argv[1:]:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print(f"{OUT} is out of date with {SOURCE}: run tools/gen_units.py", file=sys.stderr)
            return 1
        print(f"{OUT.name} matches {SOURCE.name}")
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
